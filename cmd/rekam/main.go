// defaultListenAddr is where the server binds when nothing says otherwise.
//
// The solo edition binds loopback. It is the build a single person runs for
// themselves — often on a laptop or a home server — and the default should
// not put an authentication surface on whatever network they happen to be
// attached to. Reaching it from another machine is a deliberate act:
// `--addr 0.0.0.0:5000`, or REKAM_ADDR.
//
// Team and managed bind all interfaces, because being reached from elsewhere
// is the entire point of running them. (rekam.net binds loopback anyway, via
// REKAM_ADDR, because cloudflared is the only thing that should reach it.)
func defaultListenAddr() string {
	if api.Edition == "solo" {
		return "127.0.0.1:5000"
	}
	return ":5000"
}
