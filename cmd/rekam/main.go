// ── helpers ───────────────────────────────────────────────────────────────────

func defaultInstallDir() string {
	if h, err := os.UserHomeDir(); err == nil {
		return filepath.Join(h, ".rekam")
	}
	return ".rekam"
}

func currentUser() string {
	if u, err := user.Current(); err == nil && u.Username != "" {
		return u.Username
	}
	return "user"
}

func isSystemd() bool {
	_, err := os.Stat("/run/systemd/system")
	return err == nil
}

// installUserService writes a ~/.config/systemd/user/rekam.service and enables it.
// No sudo required.
func installUserService(dir, _ string, envPath string) error {
	exe, err := os.Executable()
	if err != nil {
		return err
	}
	unitDir := filepath.Join(os.Getenv("HOME"), ".config", "systemd", "user")
	if err := os.MkdirAll(unitDir, 0755); err != nil {
		return err
	}
	unit := fmt.Sprintf(`[Unit]
Description=rekam OS
After=default.target

[Service]
ExecStart=%s serve
EnvironmentFile=%s
Restart=on-failure
WorkingDirectory=%s
KillMode=mixed
TimeoutStopSec=15

[Install]
WantedBy=default.target
`, exe, envPath, dir)
	unitPath := filepath.Join(unitDir, "rekam.service")
	if err := os.WriteFile(unitPath, []byte(unit), 0644); err != nil {
		return err
	}
	// daemon-reload, enable, start
	for _, args := range [][]string{
		{"--user", "daemon-reload"},
		{"--user", "enable", "--now", "memory"},
	} {
		cmd := exec.Command("systemctl", args...)
		cmd.Stderr = os.Stderr
		if err := cmd.Run(); err != nil {
			return fmt.Errorf("systemctl %v: %w", args, err)
		}
	}
	return nil
}

// startBackground launches `rekam serve` as a detached background process
// and writes its PID to dir/rekam.pid. Used on non-systemd hosts.
func startBackground(dir string) error {
	exe, err := os.Executable()
	if err != nil {
		return err
	}
	cmd := exec.Command(exe, "serve")
	cmd.Stdout = mustCreateFile(filepath.Join(dir, "server.log"))
	cmd.Stderr = cmd.Stdout
	cmd.SysProcAttr = &syscall.SysProcAttr{Setsid: true}
	if err := cmd.Start(); err != nil {
		return err
	}
	pid := fmt.Sprintf("%d\n", cmd.Process.Pid)
	return os.WriteFile(filepath.Join(dir, "rekam.pid"), []byte(pid), 0644)
}

// ── stop ──────────────────────────────────────────────────────────────────────

func cmdStop(args []string) {
	fs := flag.NewFlagSet("stop", flag.ExitOnError)
	dir := fs.String("dir", defaultInstallDir(), "install directory")
	fs.Parse(args)

	if isSystemd() {
		cmd := exec.Command("systemctl", "--user", "stop", "memory")
		cmd.Stdout = os.Stdout
		cmd.Stderr = os.Stderr
		fatalf(cmd.Run(), "systemctl stop")
		fmt.Println("stopped")
		return
	}

	fatalf(stopBackground(*dir), "stop")
	fmt.Println("stopped")
}

// ── restart ───────────────────────────────────────────────────────────────────

func cmdRestart(args []string) {
	fs := flag.NewFlagSet("restart", flag.ExitOnError)
	dir := fs.String("dir", defaultInstallDir(), "install directory")
	fs.Parse(args)

	if isSystemd() {
		cmd := exec.Command("systemctl", "--user", "restart", "memory")
		cmd.Stdout = os.Stdout
		cmd.Stderr = os.Stderr
		fatalf(cmd.Run(), "systemctl restart")
		fmt.Println("restarted")
		return
	}

	// Stop existing process (warn if the PID file is missing/invalid), then start anew.
	if err := stopBackground(*dir); err != nil {
		fmt.Printf("note: not stopping existing server: %v\n", err)
	}
	fatalf(startBackground(*dir), "start")
	fmt.Println("restarted")
}

// stopBackground kills the process recorded in dir/rekam.pid.
func stopBackground(dir string) error {
	pidPath := filepath.Join(dir, "rekam.pid")
	data, err := os.ReadFile(pidPath)
	if err != nil {
		return fmt.Errorf("no pid file found at %s (is the server running?)", pidPath)
	}
	pidStr := strings.TrimSpace(string(data))
	pid, err := strconv.Atoi(pidStr)
	if err != nil {
		return fmt.Errorf("invalid pid %q: %w", pidStr, err)
	}
	proc, err := os.FindProcess(pid)
	if err != nil {
		return fmt.Errorf("find process %d: %w", pid, err)
	}
	if err := proc.Signal(syscall.SIGTERM); err != nil {
		return fmt.Errorf("signal %d: %w", pid, err)
	}
	os.Remove(pidPath)
	return nil
}

func mustCreateFile(path string) *os.File {
	f, err := os.OpenFile(path, os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0644)
	if err != nil {
		return os.Stderr
	}
	return f
}

// normalizeAddr ensures the address has a colon prefix (e.g. "5000" → ":5000").
func normalizeAddr(addr string) string {
	if addr != "" && !strings.Contains(addr, ":") {
		return ":" + addr
	}
	return addr
}

// autoLoadEnv loads ~/.rekam/.env if REKAM_REGISTRY is not already set.
// This lets `rekam serve` work without requiring the user to source the file.
func autoLoadEnv() {
	if os.Getenv("REKAM_REGISTRY") != "" {
		return
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return
	}
	envPath := filepath.Join(home, ".rekam", ".env")
	data, err := os.ReadFile(envPath)
	if err != nil {
		return
	}
	for line := range strings.SplitSeq(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		k, v, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}
		if os.Getenv(k) == "" {
			os.Setenv(k, v)
		}
	}
}

// warnDefaultPassword logs a one-line warning when a login password is still the
// insecure built-in default, so a production deployment is nudged to set its own.
func warnDefaultPassword(envVar, value string) {
	if value == "test" {
		fmt.Fprintf(os.Stderr, "warning: %s is the default \"test\" — set it before exposing rekam publicly\n", envVar)
	}
}

// bootstrapAdmin ensures at least one admin account exists so the admin console
// is reachable. If none exists it prefers to adopt the master-key identity
// (REKAM_API_KEY) as the admin — attaching email + password + is_admin while
// keeping its existing memory — so an upgraded single-user install keeps its
// data reachable via the web login. Otherwise it creates a fresh admin account.
// Credentials come from REKAM_ADMIN_EMAIL (default admin@rekam.local) and
// REKAM_ADMIN_PASSWORD (default "test").
func bootstrapAdmin(eng *engine.Engine, usersDir, masterKey string) {
	exists, err := eng.AdminExists()
	if err != nil {
		fmt.Fprintf(os.Stderr, "warning: admin bootstrap check failed: %v\n", err)
		return
	}
	if exists {
		return
	}
	email := envOr("REKAM_ADMIN_EMAIL", "admin@rekam.local")
	password := envOr("REKAM_ADMIN_PASSWORD", "test")
	warnDefaultPassword("REKAM_ADMIN_PASSWORD", password)

	// Prefer adopting the existing master identity so its memory stays reachable.
	if masterKey != "" {
		if id, err := eng.PromoteToAdmin(masterKey, email, password); err == nil {
			fmt.Fprintf(os.Stderr, "adopted master identity %q as admin: %s (log in via the web UI)\n", id.Name, email)
			return
		}
	}

	memoryPath := filepath.Join(usersDir, "admin.rekam")
	if _, err := eng.CreateUser("admin", email, password, memoryPath, true, true); err != nil {
		fmt.Fprintf(os.Stderr, "warning: could not bootstrap admin account: %v\n", err)
		return
	}
	fmt.Fprintf(os.Stderr, "bootstrapped admin account: %s (log in via the web UI)\n", email)
}

func generateKey() (string, error) {
	b := make([]byte, 32)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return "mkey_" + hex.EncodeToString(b), nil
}

func fatalf(err error, msg string) {
	if err != nil {
		fmt.Fprintf(os.Stderr, "error: %s: %v\n", msg, err)
		os.Exit(1)
	}
}

func envOr(key, def string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return def
}

func envInt(key string, def int) int {
	if v := os.Getenv(key); v != "" {
		if n, err := strconv.Atoi(v); err == nil {
			return n
		}
	}
	return def
}

